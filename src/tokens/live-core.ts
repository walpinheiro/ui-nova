export type TokenName = (typeof KNOWN_TOKENS)[number]

/** Define um token ao vivo (ex.: setToken('--v-color-primary', '#000')). */
export function setToken(name: string, value: string): void {
  const el = root()
  if (!el) return
  el.style.setProperty(name, value)
  changed.add(name)
}

/** Restaura todos os tokens alterados via setToken para o valor do CSS (respeita o tema ativo). */
export function resetTokens(): void {
  const el = root()
  if (!el) return
  for (const name of changed) el.style.removeProperty(name)
  changed.clear()
}

/** Lista os tokens --v-* ativos (nome/valor computado). */
export function listTokens(): Array<{ name: string; value: string }> {
  const el = root()
  if (!el || typeof getComputedStyle === 'undefined') return []
  const styles = getComputedStyle(el)
  const out: Array<{ name: string; value: string }> = []
  for (let i = 0; i < styles.length; i++) {
    const name = styles[i]
    if (name.startsWith('--v-')) out.push({ name, value: styles.getPropertyValue(name).trim() })
  }
  return out.sort((a, b) => a.name.localeCompare(b.name))
}
